#!/usr/bin/env python3
"""
Genera 02_datos.sql (INSERTs para Oracle) a partir de los mismos CSV que
alimentan PostgreSQL, para que ambos motores trabajen con datos idénticos.

Subconjunto: todos los catálogos + los primeros N envíos (por defecto 1000),
sus clientes y sus eventos de tracking.
Uso: python generar_inserts_oracle.py [n_envios]
"""
import csv
import os
import sys

N = int(sys.argv[1]) if len(sys.argv) > 1 else 1000
BASE = os.path.dirname(os.path.abspath(__file__))
DATOS = os.path.join(BASE, '..', '01_Relacional_PostgreSQL', 'datos')


def leer(nombre):
    with open(os.path.join(DATOS, f'{nombre}.csv'), encoding='utf-8') as f:
        return list(csv.DictReader(f))


def txt(v):
    return 'NULL' if v == '' else "'" + v.replace("'", "''") + "'"


def num(v):
    return 'NULL' if v == '' else v


def boolean(v):
    return 'TRUE' if v == 't' else 'FALSE'


def tstz(v):  # '2026-04-01 08:15:00-05' -> TO_TIMESTAMP_TZ
    if v == '':
        return 'NULL'
    return f"TO_TIMESTAMP_TZ('{v[:19]} {v[19:]}:00', 'YYYY-MM-DD HH24:MI:SS TZH:TZM')"


def fecha(v):
    return 'NULL' if v == '' else f"DATE '{v}'"


envios = leer('envio')[:N]
ids_envio = {e['id_envio'] for e in envios}
ids_cliente = {e['id_cliente'] for e in envios}
eventos = [e for e in leer('evento_tracking') if e['id_envio'] in ids_envio]
clientes = [c for c in leer('cliente') if c['id_cliente'] in ids_cliente]

out = []
w = out.append
w('-- Generado por generar_inserts_oracle.py: datos idénticos a PostgreSQL (subconjunto)')
w('SET DEFINE OFF')
w('SET FEEDBACK OFF')
w('ALTER SESSION SET TIME_ZONE = \'America/Lima\';')

for r in leer('region'):
    w(f"INSERT INTO region VALUES ({r['id_region']}, {txt(r['codigo'])}, {txt(r['nombre'])}, {txt(r['nodo'])});")
for c in leer('ciudad'):
    w(f"INSERT INTO ciudad VALUES ({c['id_ciudad']}, {txt(c['nombre'])}, {txt(c['departamento'])}, {c['id_region']}, "
      f"{txt(c['ubigeo'])}, {boolean(c['tiene_aeropuerto'])}, {boolean(c['acceso_terrestre'])}, {c['latitud']}, {c['longitud']});")
# los hubs se insertan en orden de jerarquía (el padre antes que el hijo)
hubs = sorted(leer('hub'), key=lambda h: (h['id_hub_padre'] != '', int(h['id_hub'])))
for h in hubs:
    w(f"INSERT INTO hub VALUES ({h['id_hub']}, {txt(h['codigo'])}, {txt(h['nombre'])}, {txt(h['tipo'])}, {h['id_ciudad']}, "
      f"{num(h['id_hub_padre'])}, {h['capacidad_hora']}, TRUE);")
for s in leer('tipo_servicio'):
    w(f"INSERT INTO tipo_servicio VALUES ({s['id_servicio']}, {txt(s['codigo'])}, {txt(s['nombre'])}, {txt(s['modalidad'])}, "
      f"{s['sla_horas']}, {s['peso_max_kg']});")
for t in leer('tarifa'):
    w(f"INSERT INTO tarifa VALUES ({t['id_tarifa']}, {t['id_servicio']}, {t['id_region_origen']}, {t['id_region_destino']}, "
      f"{t['precio_base']}, {t['precio_kg_adicional']}, {fecha(t['vigente_desde'])}, {fecha(t['vigente_hasta'])});")
for c in clientes:
    w(f"INSERT INTO cliente VALUES ({c['id_cliente']}, {txt(c['tipo_cliente'])}, {txt(c['tipo_documento'])}, "
      f"{txt(c['nro_documento'])}, {txt(c['nombre_razon_social'])}, {txt(c['email'])}, {txt(c['telefono'])}, "
      f"{c['id_ciudad']}, {fecha(c['fecha_registro'])});")
for e in envios:
    w(f"INSERT INTO envio VALUES ({e['id_envio']}, {txt(e['nro_tracking'])}, {e['id_cliente']}, {e['id_servicio']}, "
      f"{e['id_hub_origen']}, {e['id_hub_destino']}, {tstz(e['fecha_registro'])}, {tstz(e['fecha_compromiso'])}, "
      f"{txt(e['estado_actual'])}, {e['peso_total_kg']}, {e['monto_total']}, {tstz(e['fecha_entrega'])});")
for v in eventos:
    w(f"INSERT INTO evento_tracking VALUES ({v['id_evento']}, {v['id_envio']}, {txt(v['tipo_evento'])}, {v['id_hub']}, "
      f"{tstz(v['fecha_hora'])}, {txt(v['observacion'])});")

w('COMMIT;')
# sincronizar las columnas IDENTITY con los IDs cargados (equivalente a setval en PostgreSQL)
for tabla, col in [('ciudad', 'id_ciudad'), ('hub', 'id_hub'), ('tarifa', 'id_tarifa'), ('cliente', 'id_cliente'),
                   ('envio', 'id_envio'), ('evento_tracking', 'id_evento')]:
    w(f'ALTER TABLE {tabla} MODIFY {col} GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH LIMIT VALUE);')
w('SET FEEDBACK ON')
w("SELECT 'region' tabla, COUNT(*) filas FROM region UNION ALL SELECT 'ciudad', COUNT(*) FROM ciudad "
  "UNION ALL SELECT 'hub', COUNT(*) FROM hub UNION ALL SELECT 'tipo_servicio', COUNT(*) FROM tipo_servicio "
  "UNION ALL SELECT 'tarifa', COUNT(*) FROM tarifa UNION ALL SELECT 'cliente', COUNT(*) FROM cliente "
  "UNION ALL SELECT 'envio', COUNT(*) FROM envio UNION ALL SELECT 'evento_tracking', COUNT(*) FROM evento_tracking;")

with open(os.path.join(BASE, '02_datos.sql'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('\n'.join(out) + '\n')
print(f'02_datos.sql: {len(clientes)} clientes, {len(envios)} envíos, {len(eventos)} eventos')
