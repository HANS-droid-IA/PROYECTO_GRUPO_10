CREATE TABLE operacion.despacho (
    id_despacho         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_manifiesto   VARCHAR(20)  NOT NULL UNIQUE,
    id_ruta             INTEGER      NOT NULL REFERENCES maestro.ruta (id_ruta),
    id_vehiculo         INTEGER      REFERENCES maestro.vehiculo (id_vehiculo),
    nro_vuelo           VARCHAR(8)   CHECK (nro_vuelo ~ '^[A-Z0-9]{2}[0-9]{3,4}$'),
    fecha_salida_prog   TIMESTAMPTZ  NOT NULL,
    fecha_salida_real   TIMESTAMPTZ,
    fecha_llegada_real  TIMESTAMPTZ,
    estado              VARCHAR(10)  NOT NULL DEFAULT 'PROGRAMADO'
                        CHECK (estado IN ('PROGRAMADO', 'EN_RUTA', 'ARRIBADO', 'CANCELADO')),
    -- un despacho usa vehículo propio (terrestre) o vuelo comercial (aéreo), nunca ambos
    CONSTRAINT ck_despacho_transporte CHECK ((id_vehiculo IS NULL) <> (nro_vuelo IS NULL)),
    CONSTRAINT ck_despacho_fechas CHECK (fecha_llegada_real IS NULL OR fecha_llegada_real > fecha_salida_real),
    CONSTRAINT ck_despacho_estado CHECK (
        (estado = 'PROGRAMADO' AND fecha_salida_real IS NULL) OR
        (estado = 'EN_RUTA'    AND fecha_salida_real IS NOT NULL AND fecha_llegada_real IS NULL) OR
        (estado = 'ARRIBADO'   AND fecha_llegada_real IS NOT NULL) OR
        (estado = 'CANCELADO'))
);
COMMENT ON TABLE operacion.despacho IS 'Manifiesto de carga: consolidación de envíos en un tramo (ruta) con salida programada';

