CREATE TABLE operacion.envio (
    id_envio           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nro_tracking       CHAR(13)      NOT NULL UNIQUE CHECK (nro_tracking ~ '^OLV[0-9]{10}$'),
    id_cliente         INTEGER       NOT NULL REFERENCES maestro.cliente (id_cliente),
    id_destinatario    INTEGER       NOT NULL REFERENCES operacion.destinatario (id_destinatario),
    id_servicio        SMALLINT      NOT NULL REFERENCES maestro.tipo_servicio (id_servicio),
    id_hub_origen      INTEGER       NOT NULL REFERENCES maestro.hub (id_hub),
    id_hub_destino     INTEGER       NOT NULL REFERENCES maestro.hub (id_hub),
    direccion_entrega  VARCHAR(150)  NOT NULL,
    fecha_registro     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    fecha_compromiso   TIMESTAMPTZ   NOT NULL,
    estado_actual      VARCHAR(15)   NOT NULL DEFAULT 'REGISTRADO'
                       CHECK (estado_actual IN ('REGISTRADO', 'ADMITIDO', 'EN_HUB', 'EN_TRANSITO', 'EN_REPARTO',
                                                'INTENTO_FALLIDO', 'ENTREGADO', 'DEVUELTO')),
    peso_total_kg      NUMERIC(7,2)  NOT NULL CHECK (peso_total_kg > 0),
    valor_declarado    NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (valor_declarado >= 0),
    monto_total        NUMERIC(10,2) NOT NULL CHECK (monto_total >= 0),
    fecha_entrega      TIMESTAMPTZ,
    CONSTRAINT ck_envio_hubs       CHECK (id_hub_origen <> id_hub_destino),
    CONSTRAINT ck_envio_compromiso CHECK (fecha_compromiso > fecha_registro),
    CONSTRAINT ck_envio_entrega    CHECK (fecha_entrega IS NULL OR fecha_entrega >= fecha_registro),
    CONSTRAINT ck_envio_entregado  CHECK ((estado_actual = 'ENTREGADO') = (fecha_entrega IS NOT NULL))
);
COMMENT ON COLUMN operacion.envio.estado_actual IS
    'Desnormalización controlada: último estado derivado de evento_tracking, mantenido por trigger';

