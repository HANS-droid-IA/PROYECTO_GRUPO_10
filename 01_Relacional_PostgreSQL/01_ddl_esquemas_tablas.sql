-- =====================================================================
-- Proyecto Final BD II - Trazabilidad de paquetería (caso Olva Courier)
-- 01 - DDL: esquemas, tablas, PK, FK, restricciones e índices
-- Motor: PostgreSQL 16   |   BD: olva_courier
-- =====================================================================
-- Arquitectura de schemas:
--   maestro   : catálogos y datos de referencia (red logística, clientes, personal)
--   operacion : datos transaccionales del ciclo de vida del envío (trazabilidad)
--   auditoria : bitácora de cambios generada por triggers
--   seguridad : tablas de soporte para políticas de acceso (RLS)
-- =====================================================================

DROP SCHEMA IF EXISTS seguridad CASCADE;
DROP SCHEMA IF EXISTS auditoria CASCADE;
DROP SCHEMA IF EXISTS operacion CASCADE;
DROP SCHEMA IF EXISTS maestro   CASCADE;

CREATE SCHEMA maestro;
CREATE SCHEMA operacion;
CREATE SCHEMA auditoria;
CREATE SCHEMA seguridad;

COMMENT ON SCHEMA maestro   IS 'Catálogos: regiones, ciudades, hubs, servicios, tarifas, rutas, vehículos, empleados y clientes';
COMMENT ON SCHEMA operacion IS 'Transacciones: envíos, paquetes, despachos, eventos de tracking, entregas, incidencias y comprobantes';
COMMENT ON SCHEMA auditoria IS 'Bitácora de cambios de estado de envíos';
COMMENT ON SCHEMA seguridad IS 'Asignación de usuarios a nodos para Row Level Security';

-- ---------------------------------------------------------------------
-- MAESTRO
-- ---------------------------------------------------------------------
CREATE TABLE maestro.region (
    id_region   SMALLINT     PRIMARY KEY,
    codigo      VARCHAR(5)   NOT NULL UNIQUE,
    nombre      VARCHAR(40)  NOT NULL UNIQUE,
    nodo        VARCHAR(10)  NOT NULL CHECK (nodo IN ('LIMA', 'NORTE', 'SUR'))
);
COMMENT ON COLUMN maestro.region.nodo IS 'Nodo de la BD distribuida que administra la región';

CREATE TABLE maestro.ciudad (
    id_ciudad         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre            VARCHAR(60)  NOT NULL,
    departamento      VARCHAR(40)  NOT NULL,
    id_region         SMALLINT     NOT NULL REFERENCES maestro.region (id_region),
    ubigeo            CHAR(6)      NOT NULL UNIQUE CHECK (ubigeo ~ '^[0-9]{6}$'),
    tiene_aeropuerto  BOOLEAN      NOT NULL DEFAULT FALSE,
    acceso_terrestre  BOOLEAN      NOT NULL DEFAULT TRUE,
    latitud           NUMERIC(9,6) CHECK (latitud  BETWEEN -19 AND 0),
    longitud          NUMERIC(9,6) CHECK (longitud BETWEEN -82 AND -68),
    CONSTRAINT uq_ciudad UNIQUE (nombre, departamento),
    CONSTRAINT ck_ciudad_accesible CHECK (tiene_aeropuerto OR acceso_terrestre)
);

CREATE TABLE maestro.hub (
    id_hub          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo          VARCHAR(12)  NOT NULL UNIQUE,
    nombre          VARCHAR(80)  NOT NULL,
    tipo            VARCHAR(15)  NOT NULL CHECK (tipo IN ('HUB_CENTRAL', 'HUB_REGIONAL', 'AGENCIA')),
    id_ciudad       INTEGER      NOT NULL REFERENCES maestro.ciudad (id_ciudad),
    id_hub_padre    INTEGER      REFERENCES maestro.hub (id_hub),
    capacidad_hora  INTEGER      NOT NULL CHECK (capacidad_hora > 0),
    direccion       VARCHAR(150),
    activo          BOOLEAN      NOT NULL DEFAULT TRUE,
    -- solo el hub central no depende de otro nodo logístico
    CONSTRAINT ck_hub_jerarquia CHECK ((tipo = 'HUB_CENTRAL') = (id_hub_padre IS NULL)),
    CONSTRAINT ck_hub_no_autorref CHECK (id_hub_padre <> id_hub)
);
COMMENT ON TABLE maestro.hub IS 'Nodos logísticos: hub central, hubs regionales y agencias (puntos de admisión/reparto)';

CREATE TABLE maestro.tipo_servicio (
    id_servicio  SMALLINT     PRIMARY KEY,
    codigo       VARCHAR(20)  NOT NULL UNIQUE,
    nombre       VARCHAR(60)  NOT NULL,
    modalidad    VARCHAR(10)  NOT NULL CHECK (modalidad IN ('AEREO', 'TERRESTRE')),
    sla_horas    SMALLINT     NOT NULL CHECK (sla_horas BETWEEN 1 AND 720),
    peso_max_kg  NUMERIC(6,2) NOT NULL CHECK (peso_max_kg > 0)
);

CREATE TABLE maestro.tarifa (
    id_tarifa            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_servicio          SMALLINT     NOT NULL REFERENCES maestro.tipo_servicio (id_servicio),
    id_region_origen     SMALLINT     NOT NULL REFERENCES maestro.region (id_region),
    id_region_destino    SMALLINT     NOT NULL REFERENCES maestro.region (id_region),
    precio_base          NUMERIC(8,2) NOT NULL CHECK (precio_base >= 0),
    precio_kg_adicional  NUMERIC(8,2) NOT NULL CHECK (precio_kg_adicional >= 0),
    vigente_desde        DATE         NOT NULL,
    vigente_hasta        DATE,
    CONSTRAINT uq_tarifa UNIQUE (id_servicio, id_region_origen, id_region_destino, vigente_desde),
    CONSTRAINT ck_tarifa_vigencia CHECK (vigente_hasta IS NULL OR vigente_hasta > vigente_desde)
);

CREATE TABLE maestro.ruta (
    id_ruta                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_hub_origen          INTEGER      NOT NULL REFERENCES maestro.hub (id_hub),
    id_hub_destino         INTEGER      NOT NULL REFERENCES maestro.hub (id_hub),
    modalidad              VARCHAR(10)  NOT NULL CHECK (modalidad IN ('AEREO', 'TERRESTRE')),
    distancia_km           NUMERIC(7,1) NOT NULL CHECK (distancia_km > 0),
    tiempo_estimado_horas  NUMERIC(5,1) NOT NULL CHECK (tiempo_estimado_horas > 0),
    activa                 BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_ruta UNIQUE (id_hub_origen, id_hub_destino, modalidad),
    CONSTRAINT ck_ruta_distinta CHECK (id_hub_origen <> id_hub_destino)
);

CREATE TABLE maestro.vehiculo (
    id_vehiculo   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa         VARCHAR(8)   NOT NULL UNIQUE CHECK (placa ~ '^[A-Z0-9]{3}-[0-9]{3}$'),
    tipo          VARCHAR(10)  NOT NULL CHECK (tipo IN ('CAMION', 'FURGONETA', 'MOTO')),
    capacidad_kg  NUMERIC(7,1) NOT NULL CHECK (capacidad_kg > 0),
    id_hub_base   INTEGER      NOT NULL REFERENCES maestro.hub (id_hub),
    activo        BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE maestro.empleado (
    id_empleado    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni            CHAR(8)      NOT NULL UNIQUE CHECK (dni ~ '^[0-9]{8}$'),
    nombres        VARCHAR(60)  NOT NULL,
    apellidos      VARCHAR(60)  NOT NULL,
    cargo          VARCHAR(15)  NOT NULL CHECK (cargo IN ('ATENCION', 'COURIER', 'OPERARIO_HUB', 'CONDUCTOR', 'SUPERVISOR')),
    id_hub         INTEGER      NOT NULL REFERENCES maestro.hub (id_hub),
    fecha_ingreso  DATE         NOT NULL,
    activo         BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE maestro.cliente (
    id_cliente           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_cliente         VARCHAR(8)   NOT NULL CHECK (tipo_cliente IN ('PERSONA', 'EMPRESA')),
    tipo_documento       VARCHAR(3)   NOT NULL CHECK (tipo_documento IN ('DNI', 'RUC', 'CE')),
    nro_documento        VARCHAR(12)  NOT NULL,
    nombre_razon_social  VARCHAR(120) NOT NULL,
    email                VARCHAR(120) CHECK (email ~* '^[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}$'),
    telefono             VARCHAR(15),
    direccion            VARCHAR(150),
    id_ciudad            INTEGER      NOT NULL REFERENCES maestro.ciudad (id_ciudad),
    fecha_registro       DATE         NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT uq_cliente_documento UNIQUE (tipo_documento, nro_documento),
    CONSTRAINT ck_cliente_documento CHECK (
        (tipo_documento = 'DNI' AND nro_documento ~ '^[0-9]{8}$') OR
        (tipo_documento = 'RUC' AND nro_documento ~ '^(10|20)[0-9]{9}$') OR
        (tipo_documento = 'CE'  AND nro_documento ~ '^[0-9]{9,12}$')),
    -- una empresa (persona jurídica) siempre se identifica con RUC 20...
    CONSTRAINT ck_cliente_empresa_ruc CHECK (tipo_cliente <> 'EMPRESA' OR nro_documento LIKE '20%')
);

-- ---------------------------------------------------------------------
-- OPERACION
-- ---------------------------------------------------------------------
CREATE TABLE operacion.destinatario (
    id_destinatario  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(120) NOT NULL,
    tipo_documento   VARCHAR(3)   CHECK (tipo_documento IN ('DNI', 'RUC', 'CE')),
    nro_documento    VARCHAR(12),
    telefono         VARCHAR(15)  NOT NULL,
    CONSTRAINT ck_dest_documento CHECK ((tipo_documento IS NULL) = (nro_documento IS NULL))
);

CREATE TABLE operacion.envio (
    id_envio           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nro_tracking       CHAR(13)      NOT NULL UNIQUE CHECK (nro_tracking ~ '^OLV[0-9]{10}$'),
    id_cliente         INTEGER       NOT NULL REFERENCES maestro.cliente (id_cliente),
    id_destinatario    INTEGER       NOT NULL REFERENCES operacion.destinatario (id_destinatario),
    id_servicio        SMALLINT      NOT NULL REFERENCES maestro.tipo_servicio (id_servicio),
    id_hub_origen      INTEGER       NOT NULL REFERENCES maestro.hub (id_hub),
    id_hub_destino     INTEGER       NOT NULL REFERENCES maestro.hub (id_hub),
    direccion_entrega  VARCHAR(150)  NOT NULL,
    fecha_registro     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    fecha_compromiso   TIMESTAMPTZ   NOT NULL,
    estado_actual      VARCHAR(15)   NOT NULL DEFAULT 'REGISTRADO'
                       CHECK (estado_actual IN ('REGISTRADO', 'ADMITIDO', 'EN_HUB', 'EN_TRANSITO', 'EN_REPARTO',
                                                'INTENTO_FALLIDO', 'ENTREGADO', 'DEVUELTO')),
    peso_total_kg      NUMERIC(7,2)  NOT NULL CHECK (peso_total_kg > 0),
    valor_declarado    NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (valor_declarado >= 0),
    monto_total        NUMERIC(10,2) NOT NULL CHECK (monto_total >= 0),
    fecha_entrega      TIMESTAMPTZ,
    CONSTRAINT ck_envio_hubs       CHECK (id_hub_origen <> id_hub_destino),
    CONSTRAINT ck_envio_compromiso CHECK (fecha_compromiso > fecha_registro),
    CONSTRAINT ck_envio_entrega    CHECK (fecha_entrega IS NULL OR fecha_entrega >= fecha_registro),
    CONSTRAINT ck_envio_entregado  CHECK ((estado_actual = 'ENTREGADO') = (fecha_entrega IS NOT NULL))
);
COMMENT ON COLUMN operacion.envio.estado_actual IS
    'Desnormalización controlada: último estado derivado de evento_tracking, mantenido por trigger';

CREATE TABLE operacion.paquete (
    id_paquete   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_envio     BIGINT       NOT NULL REFERENCES operacion.envio (id_envio) ON DELETE CASCADE,
    nro_bulto    SMALLINT     NOT NULL CHECK (nro_bulto > 0),
    peso_kg      NUMERIC(6,2) NOT NULL CHECK (peso_kg > 0),
    largo_cm     NUMERIC(5,1) NOT NULL CHECK (largo_cm > 0),
    ancho_cm     NUMERIC(5,1) NOT NULL CHECK (ancho_cm > 0),
    alto_cm      NUMERIC(5,1) NOT NULL CHECK (alto_cm > 0),
    descripcion  VARCHAR(100) NOT NULL,
    fragil       BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_paquete_bulto UNIQUE (id_envio, nro_bulto)
);

CREATE TABLE operacion.comprobante (
    id_comprobante  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_envio        BIGINT        NOT NULL UNIQUE REFERENCES operacion.envio (id_envio),
    tipo            VARCHAR(7)    NOT NULL CHECK (tipo IN ('BOLETA', 'FACTURA')),
    serie           CHAR(4)       NOT NULL CHECK (serie ~ '^[BF][0-9]{3}$'),
    numero          INTEGER       NOT NULL CHECK (numero > 0),
    fecha_emision   TIMESTAMPTZ   NOT NULL,
    subtotal        NUMERIC(10,2) NOT NULL CHECK (subtotal >= 0),
    igv             NUMERIC(10,2) NOT NULL CHECK (igv >= 0),
    total           NUMERIC(10,2) NOT NULL CHECK (total >= 0),
    metodo_pago     VARCHAR(20)   NOT NULL CHECK (metodo_pago IN ('EFECTIVO', 'TARJETA', 'BILLETERA_DIGITAL', 'CREDITO')),
    CONSTRAINT uq_comprobante_serie_numero UNIQUE (serie, numero),
    CONSTRAINT ck_comprobante_serie_tipo CHECK (LEFT(serie, 1) = LEFT(tipo, 1)),
    CONSTRAINT ck_comprobante_total CHECK (ABS(subtotal + igv - total) <= 0.01)
);

CREATE TABLE operacion.despacho (
    id_despacho         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_manifiesto   VARCHAR(20)  NOT NULL UNIQUE,
    id_ruta             INTEGER      NOT NULL REFERENCES maestro.ruta (id_ruta),
    id_vehiculo         INTEGER      REFERENCES maestro.vehiculo (id_vehiculo),
    nro_vuelo           VARCHAR(8)   CHECK (nro_vuelo ~ '^[A-Z0-9]{2}[0-9]{3,4}$'),
    fecha_salida_prog   TIMESTAMPTZ  NOT NULL,
    fecha_salida_real   TIMESTAMPTZ,
    fecha_llegada_real  TIMESTAMPTZ,
    estado              VARCHAR(10)  NOT NULL DEFAULT 'PROGRAMADO'
                        CHECK (estado IN ('PROGRAMADO', 'EN_RUTA', 'ARRIBADO', 'CANCELADO')),
    -- un despacho usa vehículo propio (terrestre) o vuelo comercial (aéreo), nunca ambos
    CONSTRAINT ck_despacho_transporte CHECK ((id_vehiculo IS NULL) <> (nro_vuelo IS NULL)),
    CONSTRAINT ck_despacho_fechas CHECK (fecha_llegada_real IS NULL OR fecha_llegada_real > fecha_salida_real),
    CONSTRAINT ck_despacho_estado CHECK (
        (estado = 'PROGRAMADO' AND fecha_salida_real IS NULL) OR
        (estado = 'EN_RUTA'    AND fecha_salida_real IS NOT NULL AND fecha_llegada_real IS NULL) OR
        (estado = 'ARRIBADO'   AND fecha_llegada_real IS NOT NULL) OR
        (estado = 'CANCELADO'))
);
COMMENT ON TABLE operacion.despacho IS 'Manifiesto de carga: consolidación de envíos en un tramo (ruta) con salida programada';

CREATE TABLE operacion.despacho_envio (
    id_despacho  BIGINT      NOT NULL REFERENCES operacion.despacho (id_despacho),
    id_envio     BIGINT      NOT NULL REFERENCES operacion.envio (id_envio),
    fecha_carga  TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (id_despacho, id_envio)
);

CREATE TABLE operacion.evento_tracking (
    id_evento    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_envio     BIGINT       NOT NULL REFERENCES operacion.envio (id_envio),
    tipo_evento  VARCHAR(16)  NOT NULL CHECK (tipo_evento IN ('ADMISION', 'SALIDA_HUB', 'LLEGADA_HUB', 'CLASIFICACION',
                                                              'EN_REPARTO', 'INTENTO_FALLIDO', 'ENTREGA', 'DEVOLUCION')),
    id_hub       INTEGER      NOT NULL REFERENCES maestro.hub (id_hub),
    id_empleado  INTEGER      REFERENCES maestro.empleado (id_empleado),
    id_despacho  BIGINT       REFERENCES operacion.despacho (id_despacho),
    fecha_hora   TIMESTAMPTZ  NOT NULL,
    observacion  VARCHAR(200),
    -- los movimientos físicos entre nodos siempre van asociados a un manifiesto
    CONSTRAINT ck_evento_despacho CHECK (tipo_evento NOT IN ('SALIDA_HUB', 'LLEGADA_HUB') OR id_despacho IS NOT NULL)
);
COMMENT ON TABLE operacion.evento_tracking IS 'Elemento diferenciador: trazabilidad de cada escaneo del envío en la red';

CREATE TABLE operacion.intento_entrega (
    id_intento          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_envio            BIGINT       NOT NULL REFERENCES operacion.envio (id_envio),
    nro_intento         SMALLINT     NOT NULL CHECK (nro_intento BETWEEN 1 AND 3),
    fecha_hora          TIMESTAMPTZ  NOT NULL,
    id_courier          INTEGER      NOT NULL REFERENCES maestro.empleado (id_empleado),
    resultado           VARCHAR(16)  NOT NULL CHECK (resultado IN ('ENTREGADO', 'AUSENTE', 'DIRECCION_ERRADA', 'RECHAZADO')),
    receptor_nombre     VARCHAR(120),
    receptor_documento  VARCHAR(12),
    CONSTRAINT uq_intento UNIQUE (id_envio, nro_intento),
    CONSTRAINT ck_intento_receptor CHECK ((resultado = 'ENTREGADO') = (receptor_nombre IS NOT NULL))
);

CREATE TABLE operacion.incidencia (
    id_incidencia  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_envio       BIGINT       NOT NULL REFERENCES operacion.envio (id_envio),
    tipo           VARCHAR(20)  NOT NULL CHECK (tipo IN ('DANO', 'PERDIDA', 'RETRASO', 'DIRECCION_INCORRECTA', 'OTRO')),
    id_hub         INTEGER      REFERENCES maestro.hub (id_hub),
    fecha_reporte  TIMESTAMPTZ  NOT NULL,
    descripcion    VARCHAR(300) NOT NULL,
    estado         VARCHAR(10)  NOT NULL DEFAULT 'ABIERTA' CHECK (estado IN ('ABIERTA', 'EN_PROCESO', 'CERRADA')),
    fecha_cierre   TIMESTAMPTZ,
    CONSTRAINT ck_incidencia_cierre CHECK ((estado = 'CERRADA') = (fecha_cierre IS NOT NULL)),
    CONSTRAINT ck_incidencia_fechas CHECK (fecha_cierre IS NULL OR fecha_cierre >= fecha_reporte)
);

-- ---------------------------------------------------------------------
-- AUDITORIA y SEGURIDAD
-- ---------------------------------------------------------------------
CREATE TABLE auditoria.log_estado_envio (
    id_log           BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_envio         BIGINT      NOT NULL,
    estado_anterior  VARCHAR(15),
    estado_nuevo     VARCHAR(15) NOT NULL,
    fecha_cambio     TIMESTAMPTZ NOT NULL DEFAULT now(),
    usuario_bd       TEXT        NOT NULL DEFAULT current_user
);

CREATE TABLE seguridad.usuario_nodo (
    usuario  NAME        PRIMARY KEY,
    nodo     VARCHAR(10) NOT NULL CHECK (nodo IN ('LIMA', 'NORTE', 'SUR'))
);

-- ---------------------------------------------------------------------
-- ÍNDICES (FKs más consultadas y patrones de acceso de tracking)
-- ---------------------------------------------------------------------
CREATE INDEX ix_ciudad_region        ON maestro.ciudad (id_region);
CREATE INDEX ix_hub_ciudad           ON maestro.hub (id_ciudad);
CREATE INDEX ix_empleado_hub         ON maestro.empleado (id_hub, cargo);
CREATE INDEX ix_cliente_ciudad       ON maestro.cliente (id_ciudad);
CREATE INDEX ix_envio_cliente        ON operacion.envio (id_cliente);
CREATE INDEX ix_envio_origen_fecha   ON operacion.envio (id_hub_origen, fecha_registro);
CREATE INDEX ix_envio_destino        ON operacion.envio (id_hub_destino);
CREATE INDEX ix_envio_estado_activo  ON operacion.envio (estado_actual, fecha_compromiso)
    WHERE estado_actual NOT IN ('ENTREGADO', 'DEVUELTO');                 -- índice parcial: solo envíos vivos
CREATE INDEX ix_despacho_ruta_salida ON operacion.despacho (id_ruta, fecha_salida_prog);
CREATE INDEX ix_desp_envio_envio     ON operacion.despacho_envio (id_envio);
CREATE INDEX ix_evento_envio_fecha   ON operacion.evento_tracking (id_envio, fecha_hora);
CREATE INDEX ix_evento_hub_fecha     ON operacion.evento_tracking (id_hub, fecha_hora);
CREATE INDEX ix_evento_despacho      ON operacion.evento_tracking (id_despacho);
CREATE INDEX ix_intento_courier      ON operacion.intento_entrega (id_courier, fecha_hora);
CREATE INDEX ix_incidencia_envio     ON operacion.incidencia (id_envio);
CREATE INDEX ix_incidencia_abierta   ON operacion.incidencia (tipo) WHERE estado <> 'CERRADA';
